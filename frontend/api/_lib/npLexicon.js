function createGlossary() {
  const seenP = new Set();
  const seenS = new Set();

  function planet(en) {
    if (!en || en === '—') return '—';
    const np = PLANET_NP[en] || en;
    if (!seenP.has(en) && PLANET_NP[en]) {
      seenP.add(en);
      return `${np} (${en})`;
    }
    return np;
  }

  function sign(en) {
    if (!en || en === '—') return '—';
    const np = SIGN_NP[en] || en;
    if (!seenS.has(en) && SIGN_NP[en]) {
      seenS.add(en);
      return `${np} (${en})`;
    }
    return np;
  }

  function nakshatra(en) {
    if (!en) return '';
    return NAKSHATRA_NP[en] || en;
  }

  function house(n) {
    return HOUSE_ORD[Number(n)] || `भाव ${n}`;
  }

  function area(n) {
    return HOUSE_AREA[Number(n)] || '';
  }

  function lord(signEn) {
    return planet(SIGN_LORD_EN[signEn] || signEn);
  }

  function grahaList(planets) {
    return (planets || []).map((p) => planet(p.name || p)).join(', ');
  }

  return { planet, sign, nakshatra, house, area, lord, grahaList };
}

