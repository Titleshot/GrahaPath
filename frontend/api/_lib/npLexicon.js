function selectYogas(yogas) {
  const seen = new Set();
  const out = [];
  for (const y of yogas || []) {
    const title = yogaTitle(y.name);
    const str = String(y.strength || '').toLowerCase();
    if (!title) continue;
    if (seen.has(title)) continue;
    if (title !== 'राजयोग' && (/weak|possible|hint/.test(str) || /hint/i.test(String(y.name || '')))) continue;
    seen.add(title);
    out.push({ title, meaning: yogaMeaning(y.name) });
    if (out.length >= 3) break;
  }
  return out;
}

