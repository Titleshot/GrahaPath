function yogaTitle(raw) {
  const n = String(raw || 'योग');
  if (/raj/i.test(n)) return 'राजयोग';
  if (/neecha|nicha|bhanga/i.test(n)) return 'नीचभङ्ग योग';
  if (/dhana|wealth|benefic/i.test(n)) return 'धनयोग';
  if (/gaja|kesari/i.test(n)) return 'गजकेसरी योग';
  if (/budha|aditya/i.test(n)) return 'बुधादित्य योग';
  if (/pancha|mahapurusha/i.test(n)) return 'पञ्चमहापुरुष योग';
  if (/saturn emphasis/i.test(n)) return '';
  if (/rahu|ketu axis/i.test(n)) return '';
  return /yoga|योग/i.test(n) ? n : '';
}

